/**
 * Every published Multiplayer and Warzone build ("subclass") per gun with its build code, shown in
 * the weapon card's Meta tab and the meta popup under that mode's meta class (MetaBuilds), each with
 * a small copy button (2026-11-12, the user's ask: "all the different multiplayer and warzone
 * subclasses, neatly with the other metas on the red gun card").
 *
 * A dated SNAPSHOT of codmunity.gg's weapon pages (/weapon/mw4/<gun>), read 2026-11-14: the build
 * cards the page shows openly (Versatile, Close range, Long range, Sniper, Sniper support, Apex
 * build), in codmunity's rank order. Its "Additional Loadouts" (Max sprint speed, Min ADS …) are
 * Premium-locked on the website and were NOT taken from the page data: our own worked-out versions
 * are in extraBuilds.ts. DMZ and Resurgence builds are left out. Builds with no date of their own
 * carry the day the page was read (`dated: false`). Generated by .claude/testing/meta-codes/
 * gen-site.mjs; refresh together with loadouts.ts.
 */
import { build, type AttachmentSlot, type Loadout } from './loadouts.ts';

export interface SiteBuild extends Loadout {
	/** The game's build code. */
	code: string;
	/** codmunity's rank among the gun's builds in that mode (1 = top). */
	rank: number;
	/** codmunity's "Pro Favorite" mark. */
	pro: boolean;
	/** false = the build card had no date; `date` is the day the page was read. */
	dated: boolean;
}

export type SiteMode = 'mp' | 'wz';

type Parts = Partial<Record<AttachmentSlot, string>>;
type Extras = { note?: string; verified?: boolean };

export const SITE_SOURCE = 'codmunity.gg';
const READ = '2026-11-14';

function site(code: string, rank: number, role: string, date: string | null, parts: Parts, pro: boolean, extras: Extras = {}): SiteBuild {
	return { ...build(role, SITE_SOURCE, date ?? READ, parts, extras), code, rank, pro, dated: date !== null };
}

